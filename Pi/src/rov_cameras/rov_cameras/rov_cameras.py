"""
A program that setups up RTSP streams for defined camera v4l2 camera interfaces.
    Camera interfaces can be found with 'v4l2-ctl --list-devices'
"""
import gi
gi.require_version('Gst', '1.0')
gi.require_version('GstRtsp', '1.0')
gi.require_version('GstRtspServer', '1.0')

from gi.repository import Gst, GstRtsp, GstRtspServer, GLib

import subprocess
import signal
import pyudev

import rclpy
from rclpy import logging
from rclpy.parameter import Parameter
from rcl_interfaces.msg import ParameterDescriptor

NODE_NAME = "rov_cameras"
DEFAULT_STRING = "default"

logger = logging.get_logger(NODE_NAME)
server_loop = GLib.MainLoop()

def shutdown_handler(signum, frame):
    logger.info("Received shutdown signal")
    server_loop.quit()


def get_camera_formats(device_file: str) -> list[str]:
    """
    Given a device file, detect and return the formats it supports.
    """
    result = subprocess.run(
        ["v4l2-ctl", "--device", device_file, "--list-formats"],
        capture_output=True,
        text=True
    )

    formats = []

    for line in result.stdout.splitlines():
        if "'" in line:
            formats.append(line.split("'")[1])

    return formats

def detect_cameras() -> dict[str: dict[str: list[str]]]:
    """
    Detects cameras based on name

    Returns
        A dictionary with camera name and device files, e.g.
            "camera name": {
                "/dev/video0": ["MJPG", "YUYV"],
                "/dev/video1": ["H264"]
            }
    """
    context = pyudev.Context()

    cameras: dict[str: dict[str: list[str]]] = {}
    for device in context.list_devices(subsystem="video4linux"):
        # Read in camera details
        device_file = device.device_node
        device_name = device.get('ID_V4L_PRODUCT')
        device_formats = get_camera_formats(device.device_node)

        # Store the data
        if device_name not in cameras:
            cameras[device_name] = {}
        cameras[device_name][device_file] = device_formats

    return cameras

def best_camera(camera_name: str, cameras: dict[str: dict[str: list[str]]]) -> tuple[str, str] | None:
    """
    Determine best camera file interface to use based on its supported formats.

    Params
        camera_name: The name of the camera
        cameras: Details on all detected cameras generated by detect_cameras()

    Returns
        (device_file, device_formats) or None if camera_name is invalid or doesn't expose output formats
    """
    if camera_name not in cameras:
        logger.error(f"{camera_name} not detected. Find camera names with 'v4l2-ctl --list-devices")
        return None
    camera_details = cameras[camera_name]
    print(camera_details)
    camera_formats = None
    camera_file = None
    for device_file, formats in camera_details.items():
        if "H264" in formats:
            camera_formats = formats
            camera_file = device_file
        elif "MJPG" in formats:
            camera_formats = formats
            camera_file = device_file
        elif len(formats) != 0:
            camera_formats = formats
            camera_file = device_file

    if camera_formats is None:
        logger.error(f"{camera_name} did not expose any formats. Find camera formats with 'v4l2-ctl --device <file> --list-formats")
        return None
    
    return (camera_file, camera_formats)


def create_factory(
        device_file: str, 
        device_formats: list[str], 
        width: int | None, 
        height: int | None, 
        framerate: int | None
    ) -> GstRtspServer.RTSPMediaFactory:
    """
    Setup RTSP factory (stream parameters) for a given device file

    Params
        device_file: Linux interface file like: "/dev/video0"
        device_formats: A list for formats like: ["H264", "MJPG", "YUYV"]
        width, height, framerate: Resolution and framerate supported by camera

    Returns
        RTSPMediaFactory
    """
    factory = GstRtspServer.RTSPMediaFactory()
    
    factory.set_address_pool(None)
    factory.set_latency(0)


    if "H264" in device_formats:
        if width is not None and height is not None and framerate is not None:
            factory.set_launch(
                f'( v4l2src device={device_file} ! '
                'video/x-h264,width=1280,height=720,'
                'stream-format=byte-stream,alignment=au ! '
                'h264parse ! '
                'rtph264pay name=pay0 pt=96 config-interval=1 )'
            )
            logger.info(f"Creating factory for {device_file} with H264 passthrough at {width}x{height}, {framerate} FPS")
        else:
            factory.set_launch(
                f'( v4l2src device={device_file} ! '
                'video/x-h264,stream-format=byte-stream,alignment=au ! '
                'rtph264pay name=pay0 pt=96 )'
            )
            logger.info(f"Creating factory for {device_file} in H264 passthrough with autonegotiated resolution")
    elif "MJPG" in device_formats:
        if width is not None and height is not None and framerate is not None:
            factory.set_launch(
                f'( v4l2src device={device_file} ! '
                f'image/jpeg,width={width},height={height},framerate={framerate}/1 !'
                'rtpjpegpay name=pay0 pt=26 )'
            )
            logger.info(f"Creating factory for {device_file} with MJPG passthrough at {width}x{height}, {framerate} FPS")
        else:
            factory.set_launch(
                f'( v4l2src device={device_file} ! '
                'image/jpeg ! '
                'jpegparse ! '
                'rtpjpegpay name=pay0 pt=26 )'
            )
            logger.info(f"Creating factory for {device_file} with MJPG passthrough and autonegotiated resolution")
    else:
        factory.set_launch(
            f"( v4l2src device={device_file} ! "
            "video/x-raw ! "
            "videoconvert ! "
            "video/x-raw,format=I420 ! "
            "x264enc tune=zerolatency speed-preset=ultrafast bitrate=2500 ! "
            "h264parse ! "
            "rtph264pay name=pay0 pt=96 config-interval=1 )"
        )
        logger.info(f"Creating factory for {device_file} in H264 encoding mode with autonegotiated resolution")

    factory.set_shared(True)

    return factory

def main():
    signal.signal(signal.SIGINT, shutdown_handler)
    signal.signal(signal.SIGTERM, shutdown_handler)

    # Setup ros2 node to read params
    rclpy.init()
    ros_node = rclpy.create_node(NODE_NAME)

    # Declare parameters
    ros_node.declare_parameter("rtsp_port", 8554)
    # List of camera names from v4l2-ctl --list-devices, "defaulty" will try to autodetect 1 camera
    ros_node.declare_parameter("camera_names", [DEFAULT_STRING])
    ros_node.declare_parameter("camera_widths", [DEFAULT_STRING])
    ros_node.declare_parameter("camera_heights", [DEFAULT_STRING])
    ros_node.declare_parameter("camera_framerates", [DEFAULT_STRING])
    # List of stream endpoints
    ros_node.declare_parameter("stream_endpoints", ["defaulty"])

    port: int = ros_node.get_parameter("rtsp_port").value
    camera_names: list = ros_node.get_parameter("camera_names").value
    camera_widths: list = ros_node.get_parameter("camera_widths").value
    camera_heights: list = ros_node.get_parameter("camera_heights").value
    camera_framerates: list = ros_node.get_parameter("camera_framerates").value
    stream_endpoints: list = ros_node.get_parameter("stream_endpoints").value

    # Validate parameters
    if len(camera_names) != len(camera_widths) or len(camera_widths) != len(camera_heights) or len(camera_framerates) != len(camera_heights) or len(camera_framerates) != len(stream_endpoints):
        logger.fatal("camera_names, camera_widths, camera_heights, camera_framerates, stream_endpoints parameters must be equal length")
        exit(-1)

    # Detect cameras
    cameras = detect_cameras()

    # Setup camera streams
    Gst.init(None)

    server = GstRtspServer.RTSPServer()
    mounts = server.get_mount_points()
    server.set_service(str(port))

    # Handle no parameters case (just uses camera at /dev/video0)
    if len(camera_names) == 1 and camera_names[0] == DEFAULT_STRING:
        factory = create_factory("/dev/video0", ["placeholder"], None, None, None)
        mounts.add_factory("/camera0", factory)
        logger.info(f"Attempt to register camera at /dev/video0 at rtsp://0.0.0.0:{port}/camera0")
    else:
        for i in range(len(camera_names)):
            # Find camera details
            camera_name = camera_names[i]
            camera_width = camera_widths[i]
            camera_height = camera_heights[i]
            camera_framerate = camera_framerates[i]
            endpoint_name = stream_endpoints[i]
            camera_details = best_camera(camera_name, cameras)
            camera_file, camera_formats = camera_details

            # Validate parameters
            if camera_details is None:
                logger.fatal(f"{camera_name} is invalid")
                exit(-1)

            if camera_width == DEFAULT_STRING or camera_height == DEFAULT_STRING or camera_framerate == DEFAULT_STRING:
                camera_width, camera_height, camera_framerate = None, None, None
            else:
                try:
                    camera_width = int(camera_width)
                    camera_height = int(camera_height)
                    camera_framerate = int(camera_framerate)

                except (ValueError, TypeError):
                    logger.error("Camera resolution and framerate must be integers")
                    return None

            # Setup streaming parameters
            factory = create_factory(camera_file, camera_formats, camera_width, camera_height, camera_framerate)
            mounts.add_factory(f"/{endpoint_name}", factory)
            logger.info(f"Registered camera {camera_name} at rtsp://0.0.0.0:{port}/{endpoint_name}")


    # Run server
    source_id = server.attach(None)
    if source_id == 0:
        logger.fatal("Failed to attach RTSP server")
        raise RuntimeError("RTSP server attachment failed")
    logger.info(f"RTSP server running on port {port}")
    server_loop.run()
    logger.info("Shutting down RTSP server...")
    ros_node.destroy_node()
    rclpy.shutdown()

if __name__ == '__main__':
    main()
